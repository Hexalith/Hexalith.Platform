using Hexalith.EventStore.Client.Processes;
using Hexalith.EventStore.Client.Projections;
using Hexalith.EventStore.DomainService;

using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.DependencyInjection.Extensions;
using Microsoft.Extensions.Diagnostics.HealthChecks;
using Microsoft.Extensions.Hosting;

namespace Hexalith.Platform.Works.Runtime;

/// <summary>Platform adapters over published SDK health and explicitly synthetic disposition seams.</summary>
public static class WorksRecoveryRuntimeExtensions
{
    /// <summary>Adds bounded cached gauges and alerts without granting disposition authority.</summary>
    /// <remarks>
    /// Platform's hosting startup and an explicitly marked parity fixture can both call this method in one host.
    /// The first call registers the telemetry; later calls add no descriptor, so gauges, alerts and publisher
    /// options are registered exactly once.
    /// </remarks>
    /// <param name="services">Host service collection.</param>
    /// <returns>The service collection.</returns>
    public static IServiceCollection AddWorksRecoveryTelemetry(this IServiceCollection services)
    {
        ArgumentNullException.ThrowIfNull(services);
        if (services.Any(static descriptor => descriptor.ServiceType == typeof(WorksRecoveryTelemetryPublisher)))
            return services;
        services.TryAddSingleton(TimeProvider.System);
        services.TryAddSingleton(provider => new WorksRecoveryTelemetryPublisher(
            provider.GetRequiredKeyedService<EventStoreDomainDiagnostics>("work"), provider.GetRequiredService<TimeProvider>()));
        services.TryAddEnumerable(ServiceDescriptor.Singleton<IHealthCheckPublisher, WorksRecoveryTelemetryPublisher>(provider => provider.GetRequiredService<WorksRecoveryTelemetryPublisher>()));
        services.Configure<HealthCheckPublisherOptions>(options =>
        {
            options.Delay = TimeSpan.Zero;
            options.Period = TimeSpan.FromSeconds(5);
            options.Timeout = TimeSpan.FromSeconds(2);
        });
        return services;
    }

    /// <summary>Installs disposable proof grants; production and unmarked fixtures always refuse.</summary>
    /// <param name="services">Host services.</param>
    /// <param name="environment">Must be Development.</param>
    /// <param name="explicitGrants">Bounded exact source list generated by the disposable fixture.</param>
    /// <param name="operatorWorkload">The named synthetic operator workload.</param>
    /// <param name="auditStateStore">State component included in rollback.</param>
    /// <returns>The service collection.</returns>
    public static IServiceCollection AddWorksSyntheticRecoveryRuntime(this IServiceCollection services, IHostEnvironment environment,
        IEnumerable<ProcessSource> explicitGrants, string operatorWorkload, string auditStateStore)
    {
        ArgumentNullException.ThrowIfNull(services);
        ArgumentNullException.ThrowIfNull(environment);
        if (!environment.IsDevelopment() || Environment.GetEnvironmentVariable("WORKS_PLATFORM_PARITY") != "1"
            || Environment.GetEnvironmentVariable("WORKS_SDK_PROOF") != "1")
            throw new InvalidOperationException("Synthetic recovery authority requires an explicitly marked disposable Development parity fixture.");
        ArgumentException.ThrowIfNullOrWhiteSpace(auditStateStore);
        var authorizer = new WorksSyntheticDispositionAuthorizer(explicitGrants, operatorWorkload);
        services.RemoveAll<IProcessDispositionAuthorizer>();
        services.RemoveAll<IProcessDispositionAuditSink>();
        services.AddSingleton(authorizer);
        services.AddSingleton<IProcessDispositionAuthorizer>(authorizer);
        services.AddSingleton<IProcessDispositionAuditSink>(provider => new WorksSyntheticDispositionAuditSink(
            provider.GetRequiredService<IReadModelStore>(), authorizer, auditStateStore, provider.GetRequiredService<TimeProvider>()));
        return services.AddWorksRecoveryTelemetry();
    }
}
